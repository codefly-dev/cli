// Package fixturefragments builds the local authority's fixture-composition
// document for a run: the merge of the fragment every module of the workspace
// ships next to its code. Each module states, once, what the local
// authority's standard fixture roles may do at its kinds
// (<module>/configurations/<profile>/fixture-composition.yaml); the
// composition's own module states only what is the composition's own (a
// collection its seed writes). The rules of the document and of the merge are
// the authority's (codefly-dev/authority libraries/fixture-composition): this
// package finds the fragments and writes the result where a service that
// declares the group reads it, as the workspace's own document.
package fixturefragments

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	fixturecomposition "github.com/codefly-dev/authority/libraries/fixture-composition/go"
	"github.com/codefly-dev/core/configurations"
	"github.com/codefly-dev/core/resources"

	"github.com/codefly-dev/cli/pkg/environments"
)

// Group is the workspace configuration group the merged document is written
// as, and the file name of every fragment.
const Group = fixturecomposition.Name

// generatedMarker starts the first line of every document this package
// writes; a file that does not start with it is hand-written and is never
// overwritten.
const generatedMarker = "# Generated by codefly from every composed module's fixture-composition fragment."

// ErrHandWritten is a workspace document that does not carry the generated
// marker: a composition's hand-written copy, which a merge never overwrites.
var ErrHandWritten = errors.New("the workspace's fixture-composition document is hand-written")

// Prepared is one environment's merged document and where it goes.
type Prepared struct {
	// Target is the workspace's own configurations/<profile>/fixture-composition.yaml.
	Target string
	// Sources names every fragment merged, sorted.
	Sources []string
	// Content is the document, generated marker first.
	Content []byte
}

// Declared reports whether a service of the workspace declares the group as a
// workspace configuration dependency: only then is there a reader for it.
func Declared(ctx context.Context, workspace *resources.Workspace) (bool, error) {
	refs, err := workspace.LoadServiceWithModules(ctx)
	if err != nil {
		return false, err
	}
	for _, ref := range refs {
		service, err := workspace.LoadService(ctx, ref)
		if err != nil {
			return false, err
		}
		if slices.Contains(service.WorkspaceConfigurationDependencies, Group) {
			return true, nil
		}
	}
	return false, nil
}

// Prepare merges the fragment of every module of the workspace for the
// environment's configuration profiles. A module's fragment is read from the
// module's own directory, under the first profile of the chain that the
// module has a directory for, as the module's other configurations are. A
// conflict between two fragments is refused naming both.
func Prepare(ctx context.Context, workspace *resources.Workspace, env *environments.Environment) (*Prepared, error) {
	profile, err := env.ConfigurationProfileName()
	if err != nil {
		return nil, err
	}
	resource, err := env.Resource()
	if err != nil {
		return nil, err
	}
	profiles, err := resource.ConfigurationProfileNames()
	if err != nil {
		return nil, err
	}
	target := filepath.Join(workspace.Dir(), "configurations", profile, Group+".yaml")
	modules, err := workspace.LoadModules(ctx)
	if err != nil {
		return nil, err
	}
	var sources []fixturecomposition.Source
	for _, module := range modules {
		dir, found, dirErr := configurations.ProfileDirectory(ctx, module.Dir(), "configurations", profiles)
		if dirErr != nil {
			return nil, fmt.Errorf("module %s: %w", module.Name, dirErr)
		}
		if !found {
			continue
		}
		path := filepath.Join(dir, Group+".yaml")
		// A module at the workspace root (a flat layout) has the output as its
		// own configuration: it is what is written, never a fragment.
		if resources.SameDir(filepath.Dir(path), filepath.Dir(target)) {
			continue
		}
		data, readErr := os.ReadFile(path)
		if errors.Is(readErr, os.ErrNotExist) {
			continue
		}
		if readErr != nil {
			return nil, fmt.Errorf("module %s: %w", module.Name, readErr)
		}
		sources = append(sources, fixturecomposition.Source{Name: sourceName(workspace, module.Name, path), Data: data})
	}
	merged, err := fixturecomposition.Merge(sources)
	if err != nil {
		return nil, err
	}
	encoded, err := fixturecomposition.Encode(merged)
	if err != nil {
		return nil, err
	}
	names := make([]string, 0, len(sources))
	for _, source := range sources {
		names = append(names, source.Name)
	}
	slices.Sort(names)
	var content bytes.Buffer
	content.WriteString(generatedMarker + " DO NOT EDIT: change a module's fragment.\n")
	content.WriteString("# `codefly run` writes it before the local authority boots; `codefly generate fixture-composition` writes it on its own.\n")
	if len(names) == 0 {
		content.WriteString("# No composed module ships a fragment.\n")
	}
	for _, name := range names {
		content.WriteString("#   " + name + "\n")
	}
	content.Write(encoded)
	return &Prepared{Target: target, Sources: names, Content: content.Bytes()}, nil
}

// sourceName is how a fragment is named in a conflict and in the document:
// the module, and where its fragment is, relative to the workspace when it is
// inside it.
func sourceName(workspace *resources.Workspace, module, path string) string {
	if rel, err := filepath.Rel(workspace.Dir(), path); err == nil && !strings.HasPrefix(rel, "..") {
		path = rel
	}
	return fmt.Sprintf("module %s (%s)", module, path)
}

// Write writes the document unless the workspace holds a hand-written one,
// which it never overwrites (ErrHandWritten). It reports whether the file
// changed.
func Write(prepared *Prepared) (bool, error) {
	existing, err := os.ReadFile(prepared.Target)
	switch {
	case errors.Is(err, os.ErrNotExist):
	case err != nil:
		return false, err
	case !bytes.HasPrefix(existing, []byte(generatedMarker)):
		return false, fmt.Errorf("%w: %s; move each module's grants into that module's fragment and what is the composition's own into its own module's, then delete it", ErrHandWritten, prepared.Target)
	case bytes.Equal(existing, prepared.Content):
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(prepared.Target), 0o755); err != nil {
		return false, err
	}
	if err := os.WriteFile(prepared.Target, prepared.Content, 0o600); err != nil {
		return false, err
	}
	return true, nil
}
