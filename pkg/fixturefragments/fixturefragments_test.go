const head = "schema: codefly.dev/authority/fixture-composition/v1\n"

// composition is a workspace composing the authority (whose local service
// declares the group), a store and a chat module, and its own playground
// module; files adds or replaces files under it.
func composition(t *testing.T, files map[string]string) *resources.Workspace {
	t.Helper()
	dir := t.TempDir()
	base := map[string]string{
		"workspace.codefly.yaml":                                                     "name: playground\nlayout: modules\nmodules:\n  - name: authority\n  - name: store\n  - name: chat\n  - name: playground\nenvironments:\n  - name: local\n",
		"modules/authority/module.codefly.yaml":                                      "kind: module\nname: authority\nservices:\n  - name: local\n",
		"modules/authority/services/local/service.codefly.yaml":                      "name: local\nversion: 0.1.0\nworkspace-configuration-dependencies:\n  - " + fixturefragments.Group + "\n",
		"modules/store/module.codefly.yaml":                                          "kind: module\nname: store\n",
		"modules/chat/module.codefly.yaml":                                           "kind: module\nname: chat\n",
		"modules/playground/module.codefly.yaml":                                     "kind: module\nname: playground\n",
		"modules/authority/configurations/local/" + fixturefragments.Group + ".yaml": head,
		"modules/store/configurations/local/" + fixturefragments.Group + ".yaml": head + `roles:
  - organization: acme
    name: viewer
    scopes:
      - {kind: documents, actions: [read]}
  - organization: acme
    name: admin
    scopes:
      - {kind: documents.collection, actions: [read, admin]}
`,
		"modules/chat/configurations/local/" + fixturefragments.Group + ".yaml": head + `roles:
  - organization: acme
    name: viewer
    scopes:
      - {kind: robin.conversations, actions: [read]}
`,
		"modules/playground/configurations/local/" + fixturefragments.Group + ".yaml": head + `roles:
  - organization: acme
    name: viewer
    scopes:
      - kind: documents.collection
        actions: [read]
        resources: [{id: "derived\x1fplayground"}]
`,
	}
	for name, content := range files {
		base[name] = content
	}
	for name, content := range base {
		if content == "" {
			continue
		}
		path := filepath.Join(dir, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoErrorf(t, err, "git init: %s", out)
	workspace, err := resources.LoadWorkspaceFromDir(context.Background(), dir)
	require.NoError(t, err)
	return workspace
}

// Two modules' fragments and the composition's own merge into the workspace's
// document, which says it is generated and reads back as the merge; a second
// write changes nothing.
func TestTheRunMergesEveryComposedModulesFragment(t *testing.T) {
	ctx := context.Background()
	workspace := composition(t, nil)
	declared, err := fixturefragments.Declared(ctx, workspace)
	require.NoError(t, err)
	require.True(t, declared)

	prepared, err := fixturefragments.Prepare(ctx, workspace, &environments.Environment{Name: "local"})
	require.NoError(t, err)
	require.Equal(t, filepath.Join(workspace.Dir(), "configurations", "local", fixturefragments.Group+".yaml"), prepared.Target)
	require.Equal(t, []string{
		"module authority (modules/authority/configurations/local/fixture-composition.yaml)",
		"module chat (modules/chat/configurations/local/fixture-composition.yaml)",
		"module playground (modules/playground/configurations/local/fixture-composition.yaml)",
		"module store (modules/store/configurations/local/fixture-composition.yaml)",
	}, prepared.Sources)

	changed, err := fixturefragments.Write(prepared)
	require.NoError(t, err)
	require.True(t, changed)
	written, err := os.ReadFile(prepared.Target)
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(string(written), "# Generated by codefly"), string(written))
	doc, err := fixturecomposition.Decode(written)
	require.NoError(t, err)
	var viewer []string
	for _, role := range doc.Roles {
		if role.Key() == "acme/viewer" {
			for _, scope := range role.Scopes {
				viewer = append(viewer, scope.Kind)
			}
		}
	}
	require.Equal(t, []string{"robin.conversations", "documents.collection", "documents"}, viewer)

	changed, err = fixturefragments.Write(prepared)
	require.NoError(t, err)
	require.False(t, changed)
}

// A composition restating a module's grant is refused naming both fragments.
func TestAConflictBetweenFragmentsNamesBoth(t *testing.T) {
	workspace := composition(t, map[string]string{
		"modules/playground/configurations/local/" + fixturefragments.Group + ".yaml": head + `roles:
  - organization: acme
    name: admin
    scopes:
      - {kind: documents.collection, actions: [read]}
`,
	})
	_, err := fixturefragments.Prepare(context.Background(), workspace, &environments.Environment{Name: "local"})
	require.ErrorIs(t, err, fixturecomposition.ErrConflict)
	require.Contains(t, err.Error(), "acme/admin's grant on documents.collection is stated by module playground (modules/playground/configurations/local/fixture-composition.yaml) and by module store (modules/store/configurations/local/fixture-composition.yaml)")
}

// A hand-written workspace document is never overwritten.
func TestAHandWrittenDocumentIsNeverOverwritten(t *testing.T) {
	handWritten := head + "# the playground's own copy\n"
	workspace := composition(t, map[string]string{
		"configurations/local/" + fixturefragments.Group + ".yaml": handWritten,
	})
	prepared, err := fixturefragments.Prepare(context.Background(), workspace, &environments.Environment{Name: "local"})
	require.NoError(t, err)
	_, err = fixturefragments.Write(prepared)
	require.True(t, errors.Is(err, fixturefragments.ErrHandWritten), err)
	require.Contains(t, err.Error(), prepared.Target)
	kept, err := os.ReadFile(prepared.Target)
	require.NoError(t, err)
	require.Equal(t, handWritten, string(kept))
}

// A workspace no service of which declares the group gets nothing written.
func TestNothingIsDeclaredWithoutTheAuthority(t *testing.T) {
	workspace := composition(t, map[string]string{
		"modules/authority/services/local/service.codefly.yaml": "name: local\nversion: 0.1.0\n",
	})
	declared, err := fixturefragments.Declared(context.Background(), workspace)
	require.NoError(t, err)
	require.False(t, declared)
}
