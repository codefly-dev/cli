var releasedBundleDigest = "sha256:" + strings.Repeat("d", 64)

// builtBundle is the identity a native run gives the bundle it built and
// retained: what a native workload of a component with a page carries.
func builtBundle() *solutionhost.FrontendPayload {
	return &solutionhost.FrontendPayload{Artifact: FrontendArtifactName, Digest: solutionhost.PayloadDigest("sha256:" + strings.Repeat("e", 64)), MediaType: "application/x-tar"}
}

// bundleModule writes a module whose package manifest declares the given
// release artifacts, with a page beside its entry service unless headless.
func bundleModule(t *testing.T, artifacts string, headless bool) (*resources.Module, []*resources.Service) {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(dir, "services", "api"), 0o755))
	files := map[string]string{
		"module.package.codefly.yaml": "kind: module-package\nschema: codefly/module-package/v2\nid: example/shared\nversion: 1.4.0\nminimum-codefly-version: '>=0.0.0'\nartifact-roots: [services]\ncontracts:\n  composition: '>=1.0'\n" + artifacts,
	}
	if !headless {
		files["services/api/"+solutionrun.FrontendFileName] = "title: Shared page\norder: 4\nexposed_module: ./Page\nhost_contract: 1\n"
	}
	for name, contents := range files {
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(contents), 0o600))
	}
	module := &resources.Module{Name: "shared", ServiceEntry: "api"}
	module.WithDir(dir)
	service := &resources.Service{Name: "api", ModuleIdentity: true, Endpoints: []*resources.Endpoint{{Name: "http", API: "http", Visibility: "internal"}}}
	return module, []*resources.Service{service}
}

// A manifest's frontend.payload is generated by both producers from the
// release's artifact metadata — the runtime artifact named frontend — and
// from nothing else: no such artifact is no payload; a bundle declared under
// another purpose, without a media type or by a headless component is refused
// by name (a name declared twice is the manifest loader's refusal).
func TestAReleasedFrontendBundleIsTheGeneratedPayload(t *testing.T) {
	bundle := "release-artifacts:\n  - name: frontend\n    purpose: runtime\n    uri: oci://registry.example/shared/frontend\n    digest: " + releasedBundleDigest + "\n    media-type: application/x-tar\n"
	cases := []struct {
		name, artifacts string
		headless        bool
		refused         string
	}{
		{name: "a declared bundle is the payload", artifacts: bundle},
		{name: "no bundle is no payload", artifacts: ""},
		{name: "under another purpose", artifacts: strings.Replace(bundle, "purpose: runtime", "purpose: source", 1), refused: "a frontend bundle is a runtime artifact"},
		{name: "without a media type", artifacts: strings.Replace(bundle, "    media-type: application/x-tar\n", "", 1), refused: "without a media type"},
		{name: "by a headless component", artifacts: bundle, headless: true, refused: "no frontend"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			module, services := bundleModule(t, tc.artifacts, tc.headless)
			env := identityEnvironment()
			env.Namespace = "example"
			pkg, artifacts, err := modulePackage(module.Dir())
			require.NoError(t, err)
			instance, undeclared, err := moduleInstanceOf(context.Background(), &resources.Workspace{Name: "example"}, module, services, env, pkg, artifacts, nil)
			deliverer := &NativeDeliverer{Workspace: &resources.Workspace{Name: "example"}, Env: env}
			var bundle *solutionhost.FrontendPayload
			if !tc.headless {
				bundle = builtBundle()
			}
			documents, nativeErr := deliverer.Render(context.Background(), &NativeWorkload{
				Module:         module,
				Services:       services,
				FrontendBundle: bundle,
				Started:        []NativeIdentity{{Module: "shared", Service: "api", Account: "shared-api", SPIFFEID: "spiffe://cluster.example/ns/example/sa/shared-api"}},
			})
			if tc.refused != "" {
				require.ErrorContains(t, err, tc.refused, "the render")
				require.ErrorContains(t, nativeErr, tc.refused, "the native delivery")
				return
			}
			require.NoError(t, err)
			require.Empty(t, undeclared)
			require.NoError(t, nativeErr)
			var want *solutionhost.FrontendPayload
			if tc.artifacts != "" {
				want = &solutionhost.FrontendPayload{Artifact: FrontendArtifactName, Digest: solutionhost.PayloadDigest(releasedBundleDigest), MediaType: "application/x-tar"}
			}
			require.Equal(t, want, instance.Frontend.Payload, "the render names the release's artifact")
			require.Equal(t, builtBundle(), documents.Frontend.Payload, "the native delivery names the bundle it built, whatever the release names")
		})
	}
}

// A native run delivers what runs: the bundle it built and retained outranks
// the release's artifact metadata on the manifest it delivers, and a bundle
// built by a headless component is refused.
func TestANativeRunStampsTheBundleItBuilt(t *testing.T) {
	bundle := "release-artifacts:\n  - name: frontend\n    purpose: runtime\n    uri: oci://registry.example/shared/frontend\n    digest: " + releasedBundleDigest + "\n    media-type: application/x-tar\n"
	built := builtBundle()
	for _, tc := range []struct {
		name, artifacts   string
		headless, unbuilt bool
		refused           string
	}{
		{name: "beside a released artifact", artifacts: bundle},
		{name: "with no released artifact", artifacts: ""},
		{name: "by a headless component", artifacts: "", headless: true, refused: "declares no frontend"},
		{name: "a declared page without a built bundle is refused", artifacts: bundle, unbuilt: true, refused: "built no bundle"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			module, services := bundleModule(t, tc.artifacts, tc.headless)
			env := identityEnvironment()
			env.Namespace = "example"
			deliverer := &NativeDeliverer{Workspace: &resources.Workspace{Name: "example"}, Env: env}
			carried := built
			if tc.unbuilt {
				carried = nil
			}
			documents, err := deliverer.Render(context.Background(), &NativeWorkload{
				Module:         module,
				Services:       services,
				FrontendBundle: carried,
				Started:        []NativeIdentity{{Module: "shared", Service: "api", Account: "shared-api", SPIFFEID: "spiffe://cluster.example/ns/example/sa/shared-api"}},
			})
			if tc.refused != "" {
				require.ErrorContains(t, err, tc.refused)
				return
			}
			require.NoError(t, err)
			require.Equal(t, built, documents.Frontend.Payload)
		})
	}
}
