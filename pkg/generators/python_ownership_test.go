// pythonFacade is a facade as the Python facade plugin writes it: its module
// docstring carries the plugin's generated-code notice.
func pythonFacade(module string) string {
	return `"""Gateway-bound facade for the ` + "`" + module + "`" + ` module — generated, do not edit.

generated by protoc-gen-codefly-facade-python from pdf.v1; do not edit
Gateway seams: unary.
"""

from __future__ import annotations

import pdf.v1.api_pb2 as pdf_v1_api_pb2


def ` + module + `(gateway):
    return gateway
`
}

// regeneratePython applies one staged Python generation to langDir — wipe
// once, merge the entry, finalize — from a raw plugin output holding the
// facade and one binding, as GenerateClientLibrary does once the companion
// has succeeded.
func regeneratePython(t *testing.T, langDir, module string) {
	t.Helper()
	raw := t.TempDir()
	for path, content := range map[string]string{
		filepath.Join(raw, module+".py"):              pythonFacade(module),
		filepath.Join(raw, "pdf", "v1", "api_pb2.py"): "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
	} {
		writeTestFile(t, path, content)
	}
	staged := &stagedLanguage{lang: languages.PYTHON, langDir: langDir, entries: []stagedEntry{{raw: raw, moduleName: module}}}
	if _, err := staged.apply("", "", "acme_pdf"); err != nil {
		t.Fatalf("apply: %v", err)
	}
}

func writeTestFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestRegeneratingAPythonLibraryKeepsWhatItDidNotWrite: the package root is
// not a purely generated directory. A regeneration removes and rewrites what
// a protoc plugin's notice says it wrote — the facade, including a stale one
// left by an earlier --module-name — and its _gen/ tree, and keeps every
// other file: a handwritten reader beside the facade, a helper quoting the
// facade's notice in its body, and the package's own __init__.py.
func TestRegeneratingAPythonLibraryKeepsWhatItDidNotWrite(t *testing.T) {
	langDir := t.TempDir()
	pkgDir := filepath.Join(langDir, "acme_pdf")
	const reader = "\"\"\"Reads a pdf through the facade.\"\"\"\n\nfrom acme_pdf.pdf import pdf\n\n\ndef read(gateway):\n    return pdf(gateway)\n"
	const quoting = "import textwrap\n\nHEADER = textwrap.dedent('''\n    generated by protoc-gen-codefly-facade-python from pdf.v1; do not edit\n''')\n"
	const initFile = "from acme_pdf.reader import read\n"
	handwritten := map[string]string{
		filepath.Join(pkgDir, "reader.py"):     reader,
		filepath.Join(pkgDir, "quoting.py"):    quoting,
		filepath.Join(pkgDir, "__init__.py"):   initFile,
		filepath.Join(pkgDir, "notes", "a.py"): "# a subpackage of the developer's\n",
	}
	for path, content := range handwritten {
		writeTestFile(t, path, content)
	}
	// What an earlier generation left: a facade under an older module name,
	// a file another protoc plugin's standard notice claims, and a binding.
	writeTestFile(t, filepath.Join(pkgDir, "old.py"), pythonFacade("old"))
	writeTestFile(t, filepath.Join(pkgDir, "api_grpc.py"), "# Code generated by protoc-gen-codefly-python. DO NOT EDIT.\n")
	writeTestFile(t, filepath.Join(pkgDir, "_gen", "stale", "v1", "api_pb2.py"), "")

	for run := 1; run <= 2; run++ {
		regeneratePython(t, langDir, "pdf")
		for path, content := range handwritten {
			got, err := os.ReadFile(path)
			if err != nil || string(got) != content {
				t.Fatalf("run %d: %s was written by hand and is kept byte for byte, got %q (%v)", run, path, got, err)
			}
		}
		for _, gone := range []string{"old.py", "api_grpc.py", filepath.Join("_gen", "stale")} {
			if _, err := os.Stat(filepath.Join(pkgDir, gone)); !os.IsNotExist(err) {
				t.Fatalf("run %d: %s was generated and is removed (stat: %v)", run, gone, err)
			}
		}
		for _, made := range []string{"pdf.py", filepath.Join("_gen", "pdf", "v1", "api_pb2.py"), filepath.Join("_gen", "__init__.py")} {
			if _, err := os.Stat(filepath.Join(pkgDir, made)); err != nil {
				t.Fatalf("run %d: %s is generated: %v", run, made, err)
			}
		}
	}
}

// TestAPythonNoticeIsReadFromTheLeadingBlockOnly: the generator a file names
// is read from the comments and the docstring it opens with, in either
// spelling, and from nothing after its first statement.
func TestAPythonNoticeIsReadFromTheLeadingBlockOnly(t *testing.T) {
	dir := t.TempDir()
	for content, want := range map[string]string{
		pythonFacade("pdf"): "protoc-gen-codefly-facade-python",
		"#!/usr/bin/env python\n# Code generated by protoc-gen-x. DO NOT EDIT.\n":    "protoc-gen-x",
		"# Code generated by codefly generate permissions. DO NOT EDIT.\n":           "codefly generate permissions",
		"\"\"\"generated by protoc-gen-y from a.v1; do not edit\"\"\"\n":             "protoc-gen-y",
		"\"\"\"A docstring.\"\"\"\n# Code generated by protoc-gen-z. DO NOT EDIT.\n": "",
		"x = 1\n# Code generated by protoc-gen-z. DO NOT EDIT.\n":                    "",
		"": "",
	} {
		path := filepath.Join(dir, "f.py")
		writeTestFile(t, path, content)
		got, err := pythonNoticeGenerator(path)
		if err != nil || got != want {
			t.Errorf("pythonNoticeGenerator(%q) = %q (%v), want %q", content, got, err, want)
		}
	}
}

// TestAFailedGenerationLeavesTheLibraryUntouched: nothing under the library is
// written until every language has generated, so a run that fails leaves the
// library byte for byte as it was — the contract it records, the generated
// facade and bindings, and the developer's own files beside them. It used to
// rewrite the contract and wipe the generated tree before the companion ran,
// so a failed run left a library with no bindings (and, before the package
// root's ownership was read from notices, no hand-written modules either).
func TestAFailedGenerationLeavesTheLibraryUntouched(t *testing.T) {
	output := t.TempDir()
	langDir := filepath.Join(output, "python")
	pkgDir := filepath.Join(langDir, "acme_pdf")
	for path, content := range map[string]string{
		filepath.Join(output, "contract", "contract.binpb"):      "the contract the library was generated from",
		filepath.Join(pkgDir, "pdf.py"):                          pythonFacade("pdf"),
		filepath.Join(pkgDir, "_gen", "pdf", "v1", "api_pb2.py"): "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
		filepath.Join(pkgDir, "reader.py"):                       "from acme_pdf.pdf import pdf\n",
		filepath.Join(pkgDir, "__init__.py"):                     "from acme_pdf.reader import read\n",
		filepath.Join(langDir, "tests", "test_reader.py"):        "def test_read():\n    pass\n",
		filepath.Join(langDir, "pyproject.toml"):                 "[project]\nname = \"acme-pdf\"\ndependencies = [\"protobuf\"]\n",
	} {
		writeTestFile(t, path, content)
	}
	before := snapshotTree(t, output)

	err := GenerateClientLibrary(context.Background(), &ClientLibraryRequest{
		Name:      "acme-pdf",
		Output:    output,
		Languages: []languages.Language{languages.PYTHON},
		Force:     true,
		Entries: []ContractEntry{{
			Endpoint: composition.APIContractEndpoint{
				Service: "api", Endpoint: "grpc", Kind: composition.APIContractKindProtobuf, Package: "pdf.v1",
			},
			// Not a descriptor set: generation fails before any companion runs.
			ContractBytes: []byte{0xff},
		}},
	})
	if err == nil {
		t.Fatal("generating from a contract that does not parse succeeded")
	}
	if after := snapshotTree(t, output); after != before {
		t.Fatalf("a failed generation changed the library:\nbefore:\n%s\nafter:\n%s", before, after)
	}
}

// snapshotTree renders every file under root as its path, mode and content.
func snapshotTree(t *testing.T, root string) string {
	t.Helper()
	var b strings.Builder
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		b.WriteString(rel + " " + info.Mode().String())
		if !d.IsDir() {
			content, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			b.WriteString(" " + string(content))
		}
		b.WriteString("\n")
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return b.String()
}
