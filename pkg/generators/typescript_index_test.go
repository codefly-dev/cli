// protoModule is a protoc-gen-es shaped binding: its header names the proto
// package, and it declares a message type, its schema and an enum — the
// export forms the real plugin emits — without importing anything, so the
// fixture compiles with no node_modules.
func protoModule(file, pkg string, messages ...string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// @generated by protoc-gen-es v2.11.0 with parameter \"target=ts\"\n")
	if pkg == "" {
		fmt.Fprintf(&b, "// @generated from file %s (syntax proto3)\n", file)
	} else {
		fmt.Fprintf(&b, "// @generated from file %s (package %s, syntax proto3)\n", file, pkg)
	}
	b.WriteString("/* eslint-disable */\n\n")
	fileConst := "file_" + strings.NewReplacer("/", "_", ".proto", "", "-", "_").Replace(file)
	fmt.Fprintf(&b, "export const %s = { name: %q };\n", fileConst, file)
	for _, message := range messages {
		if strings.HasSuffix(message, "Service") {
			fmt.Fprintf(&b, "export const %s = { typeName: %q };\n", message, pkg+"."+message)
			continue
		}
		if strings.HasPrefix(message, "enum ") {
			fmt.Fprintf(&b, "export enum %s {\n  UNSPECIFIED = 0,\n}\n", strings.TrimPrefix(message, "enum "))
			continue
		}
		fmt.Fprintf(&b, "export type %s = {\n  $typeName: %q;\n  value: string;\n};\n", message, pkg+"."+message)
		fmt.Fprintf(&b, "export const %sSchema = { typeName: %q };\n", message, pkg+"."+message)
	}
	return b.String()
}

func writeTypeScriptFixture(t *testing.T, langDir string, files map[string]string) {
	t.Helper()
	for path, content := range files {
		full := filepath.Join(langDir, "src", filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// collidingTypeScriptLibrary is what TS2308 broke on: equal names declared
// by different proto packages (Settings, WorkContextV1, an enum State), one
// package split across two files, a single-component package named like
// its facade (package api, facade api), and two packages whose names differ
// only in where the underscore sits (a_b.v1, a.b_v1).
func collidingTypeScriptLibrary() map[string]string {
	return map[string]string{
		"gen/codefly/base/v0/work_context_pb.ts":   protoModule("codefly/base/v0/work_context.proto", "codefly.base.v0", "WorkContextV1", "Settings", "enum State"),
		"gen/host/authority/v1/work_context_pb.ts": protoModule("host/authority/v1/work_context.proto", "host.authority.v1", "WorkContextV1", "enum State", "AuthorityService"),
		"gen/saas/accounts/v1/installations_pb.ts": protoModule("saas/accounts/v1/installations.proto", "saas.accounts.v1", "Installation", "Settings"),
		"gen/saas/accounts/v1/audit_pb.ts":         protoModule("saas/accounts/v1/audit.proto", "saas.accounts.v1", "AuditEvent", "AuditService"),
		"gen/api_pb.ts":                            protoModule("api.proto", "api", "Employee", "DirectoryService"),
		"gen/a_b/v1/x_pb.ts":                       protoModule("a_b/v1/x.proto", "a_b.v1", "Left"),
		"gen/a/b_v1/x_pb.ts":                       protoModule("a/b_v1/x.proto", "a.b_v1", "Right"),
		"gen/rootless_pb.ts":                       protoModule("rootless.proto", "", "Rootless"),
		"api_facade.ts": `import { DirectoryService } from "./gen/api_pb.js";

// generated by protoc-gen-codefly-facade-ts from api; do not edit

export const api = {
  New() {
    return { directory: () => DirectoryService };
  },
};

export type ApiClient = ReturnType<typeof api.New>;
`,
	}
}

// TestTypeScriptIndexNamespacesPackagesAndKeepsUniqueNamesFlat pins the
// entry point's public shape: one namespace per proto package, named from the
// package (not the file, so moving a message between files of a package
// renames nothing), the facade flat, every name only one package declares
// flat, and the colliding names listed instead of exported ambiguously.
func TestTypeScriptIndexNamespacesPackagesAndKeepsUniqueNamesFlat(t *testing.T) {
	langDir := t.TempDir()
	writeTypeScriptFixture(t, langDir, collidingTypeScriptLibrary())
	if err := writeTypeScriptIndex(langDir); err != nil {
		t.Fatal(err)
	}
	indexPath := filepath.Join(langDir, "src", "index.ts")
	first, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatal(err)
	}
	index := string(first)
	for _, want := range []string{
		`export * from "./api_facade.js";`,
		`export * as api_pb from "./packages/api.js";`,
		`export * as a__b_v1_pb from "./packages/a_b.v1.js";`,
		`export * as a_b__v1_pb from "./packages/a.b_v1.js";`,
		`export * as saas_accounts_v1_pb from "./packages/saas.accounts.v1.js";`,
		`export * from "./gen/api_pb.js";`,
		`export * from "./gen/saas/accounts/v1/audit_pb.js";`,
		`export * from "./gen/rootless_pb.js";`,
		"//   Settings: codefly_base_v0_pb.Settings, saas_accounts_v1_pb.Settings\n",
		"//   State: codefly_base_v0_pb.State, host_authority_v1_pb.State\n",
		"//   WorkContextV1: codefly_base_v0_pb.WorkContextV1, host_authority_v1_pb.WorkContextV1\n",
		// A file with a colliding name keeps the rest flat, each type-only
		// name marked so isolatedModules emits no value import for it.
		"export {\n  AuthorityService,\n  file_host_authority_v1_work_context,\n} from \"./gen/host/authority/v1/work_context_pb.js\";\n",
		"export {\n  type Installation,\n  InstallationSchema,\n  file_saas_accounts_v1_installations,\n} from \"./gen/saas/accounts/v1/installations_pb.js\";\n",
	} {
		if !strings.Contains(index, want) {
			t.Errorf("src/index.ts lacks %q\ngot:\n%s", want, index)
		}
	}
	barrel, err := os.ReadFile(filepath.Join(langDir, "src", "packages", "saas.accounts.v1.ts"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{`export * from "../gen/saas/accounts/v1/audit_pb.js";`, `export * from "../gen/saas/accounts/v1/installations_pb.js";`} {
		if !strings.Contains(string(barrel), want) {
			t.Errorf("the saas.accounts.v1 barrel lacks %s\ngot:\n%s", want, barrel)
		}
	}

	// Regeneration over its own output (packages/ and index.ts present) is a
	// fixed point.
	if err := writeTypeScriptIndex(langDir); err != nil {
		t.Fatal(err)
	}
	second, err := os.ReadFile(indexPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Fatalf("regeneration changed the barrel:\n%s\n---\n%s", first, second)
	}
}

// TestTypeScriptIndexCompiles is the check the original defect needed: TS2308
// is a compiler error, so only the compiler proves the barrel is unambiguous.
// A consumer reaching every shape — facade, flat names, each colliding name
// through its namespace — must compile under isolatedModules and
// verbatimModuleSyntax, and importing a colliding name flat must not.
func TestTypeScriptIndexCompiles(t *testing.T) {
	tsc := typeScriptCompiler(t)
	langDir := t.TempDir()
	writeTypeScriptFixture(t, langDir, collidingTypeScriptLibrary())
	if _, err := finalizeTypeScriptLibrary(langDir, "@acme/colliding-client"); err != nil {
		t.Fatal(err)
	}

	consumer := `import {
  api,
  type ApiClient,
  DirectoryService,
  type Employee,
  AuditService,
  type Installation,
  InstallationSchema,
  type Rootless,
  AuthorityService,
  codefly_base_v0_pb,
  host_authority_v1_pb,
  saas_accounts_v1_pb,
  a__b_v1_pb,
  a_b__v1_pb,
} from "./src/index.js";

export const client: ApiClient = api.New();
export const values = [DirectoryService, AuditService, InstallationSchema, AuthorityService, a__b_v1_pb.LeftSchema, a_b__v1_pb.RightSchema];
export const employee: Employee = { $typeName: "api.Employee", value: "" };
export const installation: Installation = { $typeName: "saas.accounts.v1.Installation", value: "" };
export const rootless: Rootless = { $typeName: ".Rootless", value: "" };
export const base: codefly_base_v0_pb.WorkContextV1 = { $typeName: "codefly.base.v0.WorkContextV1", value: "" };
export const host: host_authority_v1_pb.WorkContextV1 = { $typeName: "host.authority.v1.WorkContextV1", value: "" };
export const settings: saas_accounts_v1_pb.Settings = { $typeName: "saas.accounts.v1.Settings", value: "" };
export const states = [codefly_base_v0_pb.State.UNSPECIFIED, host_authority_v1_pb.State.UNSPECIFIED];
`
	if out, err := compileTypeScript(t, tsc, langDir, consumer); err != nil {
		t.Fatalf("the generated library does not compile for its consumer: %v\n%s\nindex.ts:\n%s", err, out, readFile(t, filepath.Join(langDir, "src", "index.ts")))
	}

	ambiguous := `import { WorkContextV1 } from "./src/index.js";
export type Picked = WorkContextV1;
`
	out, err := compileTypeScript(t, tsc, langDir, ambiguous)
	if err == nil || !strings.Contains(out, "TS2305") {
		t.Fatalf("importing a name two packages declare flat should fail with TS2305 (no such export), got err=%v:\n%s", err, out)
	}
}

func compileTypeScript(t *testing.T, tsc []string, langDir, consumer string) (string, error) {
	t.Helper()
	path := filepath.Join(langDir, "consumer.ts")
	if err := os.WriteFile(path, []byte(consumer), 0o644); err != nil {
		t.Fatal(err)
	}
	args := append(tsc[1:], "--noEmit", "--strict", "--skipLibCheck",
		"--target", "es2022", "--module", "esnext", "--moduleResolution", "bundler",
		"--isolatedModules", "--verbatimModuleSyntax", path)
	cmd := exec.Command(tsc[0], args...) //nolint:gosec // the test's own compiler invocation
	cmd.Dir = langDir
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// typeScriptCompiler finds tsc, or fetches the scaffold's pinned TypeScript
// through npx; without node at all the compile check cannot run.
func typeScriptCompiler(t *testing.T) []string {
	t.Helper()
	if path, err := exec.LookPath("tsc"); err == nil {
		return []string{path}
	}
	if path, err := exec.LookPath("npx"); err == nil {
		return []string{path, "--yes", "--package", "typescript@" + pinnedTypeScriptVersion, "tsc"}
	}
	t.Skip("neither tsc nor npx is on PATH; the TypeScript compile check needs node")
	return nil
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// TestTypeScriptIndexRefusesWhatOnlyAFlatNameReaches: a package's declaration
// can yield its flat name to its namespace; a facade or a package-less file
// cannot, so two of them on one name is a refusal naming both, never a barrel
// that silently drops one.
func TestTypeScriptIndexRefusesWhatOnlyAFlatNameReaches(t *testing.T) {
	for name, files := range map[string]map[string]string{
		"two facades": {
			"a_facade.ts": "export const shared = {};\n",
			"b_facade.ts": "export const shared = {};\n",
		},
		"a facade and a package-less file": {
			"a_facade.ts":        "export const Rootless = {};\n",
			"gen/rootless_pb.ts": protoModule("rootless.proto", "", "Rootless"),
		},
		"one package declaring a name twice": {
			"gen/p/v1/a_pb.ts": protoModule("p/v1/a.proto", "p.v1", "Twice"),
			"gen/p/v1/b_pb.ts": protoModule("p/v1/b.proto", "p.v1", "Twice"),
		},
		"an export the reader cannot name": {
			"gen/p/v1/a_pb.ts": protoModule("p/v1/a.proto", "p.v1", "Fine") + "export { Fine as Alias };\n",
		},
	} {
		t.Run(name, func(t *testing.T) {
			langDir := t.TempDir()
			writeTypeScriptFixture(t, langDir, files)
			if err := writeTypeScriptIndex(langDir); err == nil {
				t.Fatalf("expected a refusal, got:\n%s", readFile(t, filepath.Join(langDir, "src", "index.ts")))
			}
		})
	}
}
