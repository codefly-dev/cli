package usagelint

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	usagecontract "github.com/codefly-dev/core/contracts/usage"
	"github.com/codefly-dev/core/resources"
	"github.com/codefly-dev/core/services"
)

// GuidanceFile is where a service's coding agents read their instructions.
const GuidanceFile = "AGENTS.md"

// The markers that bound the generated block. Everything between them is
// rewritten on every sync; everything outside them is the service's own.
const (
	guidanceBegin = "<!-- codefly:usage:begin — generated by `codefly sync usage`; do not edit between these markers -->"
	guidanceEnd   = "<!-- codefly:usage:end -->"
)

// Block renders the usage rules that apply to a service as the block its
// AGENTS.md carries: one line per rule, under the owner it comes from. It is
// the short form on purpose. The reason and the alternative reach whoever
// breaks a rule through `codefly lint usage`; here an agent only needs to
// know the rule exists before it writes the code.
//
// No contract renders no block.
func Block(sources []Source) (string, error) {
	if len(sources) == 0 {
		return "", nil
	}
	var out strings.Builder
	out.WriteString(guidanceBegin + "\n")
	out.WriteString("## Usage rules of what this service consumes\n\n")
	out.WriteString("These come from the agents this service depends on, at the versions it pins.\n")
	out.WriteString("`codefly lint usage` checks the ones marked *checked* and prints, for each\nviolation, why the rule exists and what to do instead.\n")
	for _, source := range sources {
		contract, err := usagecontract.Parse([]byte(source.Document))
		if err != nil {
			return "", fmt.Errorf("usage contract of %s: %w", source.Owner, err)
		}
		fmt.Fprintf(&out, "\n### %s (%s)\n\n%s\n\n", source.Owner, source.Through, oneLine(contract.Summary))
		for i := range contract.Rules {
			rule := &contract.Rules[i]
			checked := ""
			if len(rule.Detect) > 0 {
				checked = " *(checked)*"
			}
			fmt.Fprintf(&out, "- **%s**%s %s. Do: %s", rule.ID, checked, strings.TrimSuffix(oneLine(rule.Title), "."), oneLine(rule.Do))
			if rule.Dont != "" {
				fmt.Fprintf(&out, " Don't: %s", oneLine(rule.Dont))
			}
			out.WriteString("\n")
		}
	}
	out.WriteString(guidanceEnd + "\n")
	return out.String(), nil
}

// oneLine folds a contract's text onto one line and takes the comment
// delimiters out of it, so text from a dependency can neither end the block
// early nor hide anything inside it.
func oneLine(text string) string {
	text = strings.NewReplacer("<!--", "", "-->", "").Replace(text)
	return strings.Join(strings.Fields(text), " ")
}

// Apply puts a block into a guidance file's content: in place of the block
// already there, or at the end when there is none. An empty block removes
// the one that is there. What lies outside the markers is kept byte for byte.
//
// A marker is a line that is exactly the marker, outside a fenced code
// block. A file must hold none, or one beginning followed by one end;
// anything else is refused before a byte is changed, because replacing
// between markers that do not pair deletes what a person wrote between them.
func Apply(existing, block string) (string, error) {
	begin, end, err := markers(existing)
	if err != nil {
		return "", err
	}
	if begin == nil {
		switch {
		case block == "":
			return existing, nil
		case existing == "":
			return block, nil
		case strings.HasSuffix(existing, "\n\n"):
			return existing + block, nil
		case strings.HasSuffix(existing, "\n"):
			return existing + "\n" + block, nil
		}
		return existing + "\n\n" + block, nil
	}
	before, after := existing[:begin.start], existing[end.end:]
	if block == "" {
		// Removing the block also removes the blank lines that set it apart.
		after = strings.TrimLeft(after, "\n")
		return strings.TrimRight(before, "\n") + trailing(before, after) + after, nil
	}
	return before + block + after, nil
}

// span is one line of a file by its byte offsets, line ending included.
type span struct{ start, end int }

// markers finds the block's two marker lines. It returns nil spans for a
// file with no block, and an error for any file whose markers do not form
// exactly one block.
func markers(content string) (begin, end *span, err error) {
	var begins, ends []span
	offset, fence := 0, ""
	for _, line := range strings.SplitAfter(content, "\n") {
		at := span{offset, offset + len(line)}
		offset += len(line)
		text := strings.TrimRight(line, "\r\n")
		// A fenced code block is text: a marker quoted in one, as an example,
		// is not a marker. A fence closes on a run of the character that
		// opened it, at least as long.
		if run := fenceRun(text); run != "" {
			switch {
			case fence == "":
				fence = run
			case run[0] == fence[0] && len(run) >= len(fence) && strings.TrimSpace(strings.TrimLeft(strings.TrimSpace(text), run[:1])) == "":
				fence = ""
			}
			continue
		}
		if fence != "" {
			continue
		}
		switch text {
		case guidanceBegin:
			begins = append(begins, at)
		case guidanceEnd:
			ends = append(ends, at)
		}
	}
	switch {
	case len(begins) == 0 && len(ends) == 0:
		return nil, nil, nil
	case len(begins) == 1 && len(ends) == 1 && begins[0].start < ends[0].start:
		return &begins[0], &ends[0], nil
	case len(begins) == 1 && len(ends) == 1:
		return nil, nil, fmt.Errorf("%s has the end of a usage block before its beginning; restore the markers or remove them", GuidanceFile)
	}
	return nil, nil, fmt.Errorf("%s has %d beginning and %d end marker(s) of a usage block; a file has one block or none, so restore the markers or remove them", GuidanceFile, len(begins), len(ends))
}

// fenceRun is the run of backticks or tildes that opens or closes a fenced
// code block on this line, or "" when the line is no fence.
func fenceRun(text string) string {
	trimmed := strings.TrimLeft(text, " ")
	if len(text)-len(trimmed) > 3 || len(trimmed) < 3 || (trimmed[0] != '`' && trimmed[0] != '~') {
		return ""
	}
	run := len(trimmed) - len(strings.TrimLeft(trimmed, trimmed[:1]))
	if run < 3 {
		return ""
	}
	return trimmed[:run]
}

// trailing is the line ending that follows what precedes a removed block.
func trailing(before, after string) string {
	switch {
	case strings.TrimRight(before, "\n") == "":
		return ""
	case after == "":
		return "\n"
	}
	return "\n\n"
}

// Guidance is the result of syncing one service's guidance file.
type Guidance struct {
	Service string `json:"service"`
	Path    string `json:"path"`
	Owners  int    `json:"owners"`
	// Changed is whether the file differs from what the contracts render.
	Changed bool `json:"changed"`
	// Wrote is whether the file was written (never with check).
	Wrote bool `json:"wrote"`
}

// Sync renders the usage rules that apply to a service into its AGENTS.md.
// With check it writes nothing and reports whether the file is current.
func Sync(ctx context.Context, workspace *resources.Workspace, module *resources.Module, service *resources.Service, check bool) (*Guidance, error) {
	instance, err := services.Load(ctx, workspace, module, service)
	if err != nil {
		return nil, fmt.Errorf("load service plugin: %w", err)
	}
	sources, err := gather(ctx, workspace, module, service, instance)
	if err != nil {
		return nil, err
	}
	block, err := Block(sources)
	if err != nil {
		return nil, err
	}
	path := filepath.Join(service.Dir(), GuidanceFile)
	existing, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	updated, err := Apply(string(existing), block)
	if err != nil {
		return nil, err
	}
	result := &Guidance{Service: resources.WithUnique(service).Unique(), Path: path, Owners: len(sources), Changed: updated != string(existing)}
	if !result.Changed || check {
		return result, nil
	}
	// A service that consumes nothing with rules and has no guidance file
	// gets none created for it; Changed is false in that case.
	if err := os.WriteFile(path, []byte(updated), 0o644); err != nil { //nolint:gosec // a repository document
		return nil, err
	}
	result.Wrote = true
	return result, nil
}
