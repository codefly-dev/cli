package run

import (
	"context"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/codefly-dev/core/resources"
	"github.com/stretchr/testify/require"

	"github.com/codefly-dev/cli/pkg/environments"
	"github.com/codefly-dev/cli/pkg/fixturefragments"
)

// A run writes the merged fixture-composition document before anything reads
// the configuration, and leaves a hand-written one as it stands.
func TestARunMergesTheFixtureCompositionAndKeepsAHandWrittenOne(t *testing.T) {
	dir := t.TempDir()
	head := "schema: codefly.dev/authority/fixture-composition/v1\n"
	for name, content := range map[string]string{
		"workspace.codefly.yaml":                                                 "name: playground\nlayout: modules\nmodules:\n  - name: authority\n  - name: store\nenvironments:\n  - name: local\n",
		"modules/authority/module.codefly.yaml":                                  "kind: module\nname: authority\nservices:\n  - name: local\n",
		"modules/authority/services/local/service.codefly.yaml":                  "name: local\nversion: 0.1.0\nworkspace-configuration-dependencies:\n  - " + fixturefragments.Group + "\n",
		"modules/store/module.codefly.yaml":                                      "kind: module\nname: store\n",
		"modules/store/configurations/local/" + fixturefragments.Group + ".yaml": head + "roles: [{organization: acme, name: viewer, scopes: [{kind: documents, actions: [read]}]}]\n",
	} {
		path := filepath.Join(dir, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
	}
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	require.NoErrorf(t, err, "git init: %s", out)
	ctx := context.Background()
	workspace, err := resources.LoadWorkspaceFromDir(ctx, dir)
	require.NoError(t, err)
	env := &environments.Environment{Name: "local"}
	target := filepath.Join(dir, "configurations", "local", fixturefragments.Group+".yaml")

	handWritten := head + "# the playground's own copy\n"
	require.NoError(t, os.MkdirAll(filepath.Dir(target), 0o755))
	require.NoError(t, os.WriteFile(target, []byte(handWritten), 0o600))
	require.NoError(t, provisionFixtureComposition(ctx, workspace, env))
	kept, err := os.ReadFile(target)
	require.NoError(t, err)
	require.Equal(t, handWritten, string(kept))

	require.NoError(t, os.Remove(target))
	require.NoError(t, provisionFixtureComposition(ctx, workspace, env))
	written, err := os.ReadFile(target)
	require.NoError(t, err)
	require.True(t, strings.HasPrefix(string(written), "# Generated by codefly"), string(written))
	require.Contains(t, string(written), "kind: documents")
}
