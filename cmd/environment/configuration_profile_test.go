func profileSource(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	directory := filepath.Join(root, "configurations", "hosted")
	require.NoError(t, os.MkdirAll(directory, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(directory, "platform.env"), []byte("endpoint=${endpoint:saas/accounts/authority}\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(directory, "internal-auth.secret.env"), []byte("TOKEN=\n"), 0o644))
	return root
}

func profileEnvironment(name string) *environments.Environment {
	return &environments.Environment{Name: name, ConfigurationSource: "hosted", ConfigurationProfiles: []string{name, "local"}}
}

func TestImportedProfilesSeparateSharedInputsAndEnvironmentOutputs(t *testing.T) {
	root := profileSource(t)
	for _, name := range []string{"blue", "green"} {
		require.NoError(t, materializeConfigurationProfile(t.Context(), root, profileEnvironment(name), false))
		body, err := os.ReadFile(filepath.Join(root, "configurations", name, configurations.ProfileDerivationFile))
		require.NoError(t, err)
		require.True(t, strings.HasPrefix(string(body), profileMarker))
		require.Contains(t, string(body), "derives-from: hosted")
		provided, err := configurations.LoadProfileConfigurations(t.Context(), root, "configurations", []string{name})
		require.NoError(t, err)
		values := map[string]string{}
		for _, info := range provided.Infos {
			for _, value := range info.ConfigurationValues {
				values[info.Name+"/"+value.Key] = value.Value
			}
		}
		require.Equal(t, "${endpoint:saas/accounts/authority}", values["platform/endpoint"])
	}
	blue := filepath.Join(root, "configurations", "blue")
	green := filepath.Join(root, "configurations", "green")
	require.NoError(t, os.WriteFile(filepath.Join(blue, "runnable-bindings.env"), []byte("# generated by runnable-bindings\nBLUE=resolved-blue\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(blue, "platform.env"), []byte(profileMarker+"hosted/platform.env\nendpoint=legacy-copy\n"), 0o644))
	require.NoError(t, os.Remove(filepath.Join(root, "configurations", "hosted", "platform.env")))
	require.NoError(t, materializeConfigurationProfile(t.Context(), root, profileEnvironment("blue"), false))
	_, err := os.Stat(filepath.Join(blue, "platform.env"))
	require.True(t, os.IsNotExist(err), "removed source groups retire only import-owned outputs")
	_, err = os.Stat(filepath.Join(green, configurations.ProfileDerivationFile))
	require.NoError(t, err, "importing blue never rewrites green")
	body, err := os.ReadFile(filepath.Join(blue, "runnable-bindings.env"))
	require.NoError(t, err)
	require.Contains(t, string(body), "BLUE=resolved-blue", "the runnable generator owns this file")
}

func TestImportedProfileUsesCoreStageDerivationAndValidatesInheritedSecrets(t *testing.T) {
	root := profileSource(t)
	source := filepath.Join(root, "configurations", "hosted-development")
	require.NoError(t, os.Mkdir(source, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(source, configurations.ProfileDerivationFile), []byte("derives-from: hosted\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(source, "legal.env"), []byte("ENTITY=Development fixture\n"), 0o644))
	env := profileEnvironment("blue")
	env.ConfigurationSource = "hosted-development"
	require.NoError(t, materializeConfigurationProfile(t.Context(), root, env, false))
	provided, err := configurations.LoadProfileConfigurations(t.Context(), root, "configurations", []string{"blue", "local"})
	require.NoError(t, err)
	groups := map[string]bool{}
	for _, info := range provided.Infos {
		groups[info.Name] = true
	}
	require.True(t, groups["platform"])
	require.True(t, groups["legal"])
	require.NoError(t, materializeConfigurationProfile(t.Context(), root, profileEnvironment("production"), false))
	production, err := configurations.LoadProfileConfigurations(t.Context(), root, "configurations", []string{"production", "local"})
	require.NoError(t, err)
	for _, info := range production.Infos {
		require.NotEqual(t, "legal", info.Name)
	}
	require.NoError(t, os.WriteFile(filepath.Join(root, "configurations", "hosted", "internal-auth.secret.env"), []byte("TOKEN=fixture-value\n"), 0o600))
	env = profileEnvironment("green")
	env.ConfigurationSource = "hosted-development"
	err = materializeConfigurationProfile(t.Context(), root, env, false)
	require.ErrorContains(t, err, "empty placeholders only")
	require.NotContains(t, err.Error(), "fixture-value")
	_, err = os.Stat(filepath.Join(root, "configurations", "green"))
	require.True(t, os.IsNotExist(err))
}

