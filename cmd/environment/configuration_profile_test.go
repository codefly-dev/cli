func TestProfileImportRefusesAuthoredOrSymlinkedFiles(t *testing.T) {
	for _, symlink := range []bool{false, true} {
		t.Run(map[bool]string{false: "authored", true: "symlink"}[symlink], func(t *testing.T) {
			root := profileSource(t)
			directory := filepath.Join(root, "configurations", "blue")
			require.NoError(t, os.Mkdir(directory, 0o755))
			path := filepath.Join(directory, "platform.env")
			if symlink {
				require.NoError(t, os.Symlink(filepath.Join(root, "configurations", "hosted", "platform.env"), path))
			} else {
				require.NoError(t, os.WriteFile(path, []byte("authored=true\n"), 0o644))
			}
			require.Error(t, materializeConfigurationProfile(t.Context(), root, profileEnvironment("blue"), false))
		})
	}
}
